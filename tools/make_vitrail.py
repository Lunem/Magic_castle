"""Generate the stained-glass SVGs in textures/ (one per window design).

Usage: python3 tools/make_vitrail.py
Each SVG can also be edited by hand (Figma, Illustrator, Inkscape): the page maps
the whole image onto the oval window, so keep the frame size and the centred oval.
"""
import math, os, random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEAD = "#22142c"


class Oval:
    """Drawing helper: points given in unit-circle space, stretched onto the oval."""

    def __init__(self, w, h):
        self.w, self.h, self.cx, self.cy = w, h, w / 2, h / 2
        self.out = []

    def P(self, r, deg):
        a = math.radians(deg)
        return (self.cx + r * math.cos(a) * self.w / 2, self.cy - r * math.sin(a) * self.h / 2)

    def poly(self, pts, fill):
        self.out.append(f'<polygon points="{" ".join(f"{x:.1f},{y:.1f}" for x, y in pts)}" fill="{fill}"/>')

    def ellipse(self, r, fill="none", stroke=None, width=0, extra=""):
        s = f' stroke="{stroke}" stroke-width="{width}"' if stroke else ""
        self.out.append(f'<ellipse cx="{self.cx}" cy="{self.cy}" rx="{self.w/2*r:.2f}" ry="{self.h/2*r:.2f}" fill="{fill}"{s}{extra}/>')

    def line(self, a, b, stroke, width):
        (x1, y1), (x2, y2) = a, b
        self.out.append(f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{stroke}" stroke-width="{width}"/>')

    def ring(self, r_out, r_in, colors, n):
        for k in range(n):
            a0, a1 = k * 360 / n, (k + 1) * 360 / n
            pts = [self.P(r_out, a0 + (a1 - a0) * t / 4) for t in range(5)] + [self.P(r_in, a1 - (a1 - a0) * t / 4) for t in range(5)]
            self.poly(pts, colors[k % len(colors)])

    def star_point(self, deg, tip, inner, light, dark, spread=22.5):
        """One star point split in a light and a dark half."""
        t, c = self.P(tip, deg), self.P(0, 0)
        self.poly([c, self.P(inner, deg + spread), t], light)
        self.poly([c, t, self.P(inner, deg - spread)], dark)

    def diamond(self, r, fill):
        self.poly([self.P(r, a) for a in (90, 0, 270, 180)], fill)

    def svg(self, title, defs=""):
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w*2}" height="{self.h*2}" viewBox="0 0 {self.w} {self.h}">\n'
                f"<!-- {title}. Generated by tools/make_vitrail.py -->\n"
                f'<defs>\n  <clipPath id="oval"><ellipse cx="{self.cx}" cy="{self.cy}" rx="{self.w/2}" ry="{self.h/2}"/></clipPath>\n'
                f'  <radialGradient id="light" cx="50%" cy="45%" r="60%"><stop offset="0" stop-color="#fff" stop-opacity="0.22"/>'
                f'<stop offset="1" stop-color="#fff" stop-opacity="0"/></radialGradient>\n{defs}</defs>\n'
                + "\n".join(self.out)
                + f'\n<rect width="{self.w}" height="{self.h}" fill="url(#light)" clip-path="url(#oval)"/>\n</svg>\n')


def tour_g():
    """Lower front oval (Tour G): gold and blue compass star on a sky disc, harlequin field."""
    random.seed(7)
    o = Oval(300, 500)                     # 28 x 46.8 mm window
    o.out.append(f'<rect width="{o.w}" height="{o.h}" fill="{LEAD}"/>')
    o.out.append(f'<g clip-path="url(#oval)" stroke="{LEAD}" stroke-width="2.2" stroke-linejoin="round">')
    o.ring(1.02, 0.86, ["#e8426e", "#f7a8c8", "#b45fd0", "#f6b98a", "#f26aa6", "#8a5be0"], 40)
    o.out.append(f'</g><g clip-path="url(#field)" stroke="{LEAD}" stroke-width="2" stroke-linejoin="round">')
    lat, s = ["#f59cc9", "#d7a6ef", "#f8c08f", "#ef7f95", "#fbd0e2", "#c58be6", "#f4a77c"], 26
    for j in range(-1, int(o.h / (s / 2)) + 2):
        for i in range(-1, int(o.w / s) + 2):
            x, y = i * s + (s / 2 if j % 2 else 0), j * s / 2
            o.poly([(x, y - s / 2), (x + s / 2, y), (x, y + s / 2), (x - s / 2, y)], random.choice(lat))
    o.ellipse(0.70, "url(#sky)")
    o.ellipse(0.46, "#86d6f7", extra=' fill-opacity="0.55"')
    for k in range(8):
        main = k % 2 == 0
        o.star_point(k * 45, 0.95 if main else 0.68, 0.27, *(("#ffe07a", "#f39a2b") if main else ("#4d63d8", "#1f2a86")))
    o.diamond(0.19, "#e8238f")
    o.diamond(0.095, "#ff8fcf")
    for a, b in ((90, 270), (0, 180)):
        o.line(o.P(0.19, a), o.P(0.19, b), "#b0123f", 2)
    o.out.append("</g>")
    o.ellipse(0.86, stroke=LEAD, width=3)
    o.ellipse(0.70, stroke=LEAD, width=2.5)
    o.ellipse(1 - 3 / o.w, stroke=LEAD, width=3)
    defs = (f'  <clipPath id="field"><ellipse cx="{o.cx}" cy="{o.cy}" rx="{o.w/2*0.86}" ry="{o.h/2*0.86}"/></clipPath>\n'
            '  <radialGradient id="sky" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#9fe3ff"/>'
            '<stop offset="0.6" stop-color="#3fb0ea"/><stop offset="1" stop-color="#2a6fd0"/></radialGradient>\n')
    return o.svg("Stained glass, lower front oval (Tour G)", defs)


def donjon():
    """Keep oval: turquoise and navy compass star on pink rays, crimson square centre."""
    o = Oval(300, 444)                     # 18.8 x 27.8 mm window
    o.out.append(f'<rect width="{o.w}" height="{o.h}" fill="{LEAD}"/>')
    o.out.append(f'<g clip-path="url(#oval)" stroke="{LEAD}" stroke-width="2" stroke-linejoin="round">')
    o.ellipse(1.02, "url(#rose)")
    for k in range(16):                    # pink background cut into sectors
        o.line(o.P(0, 0), o.P(1.05, k * 22.5 + 11.25), LEAD, 1.6)
    for k in range(8):                     # small violet points between the arms
        o.star_point(k * 45 + 22.5, 0.56, 0.17, "#b35bc9", "#7a2f9e", spread=13)
    for k in range(4):                     # navy diagonals
        o.star_point(k * 90 + 45, 0.80, 0.25, "#4b5fc8", "#25307f")
    for k in range(4):                     # long turquoise points reaching the rim
        o.star_point(k * 90, 0.97, 0.28, "#5fd8cc", "#1c98a0")
    o.diamond(0.24, "#a8124a")
    o.diamond(0.17, "#e0457b")
    o.diamond(0.09, "#8a0f3a")
    o.out.append("</g>")
    o.ellipse(0.955, stroke="#1c98a0", width=4)    # thin turquoise rim
    o.ellipse(0.93, stroke="#c2185b", width=1.5)   # and a red line inside it
    o.ellipse(1 - 3 / o.w, stroke=LEAD, width=3)
    defs = ('  <radialGradient id="rose" cx="50%" cy="50%" r="50%"><stop offset="0" stop-color="#fbc3dc"/>'
            '<stop offset="0.7" stop-color="#f08bb4"/><stop offset="1" stop-color="#e2669c"/></radialGradient>\n')
    return o.svg("Stained glass, keep oval (Donjon)", defs)


DESIGNS = {"vitrail-tour-g.svg": tour_g, "vitrail-donjon.svg": donjon}

if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "textures"), exist_ok=True)
    for name, make in DESIGNS.items():
        path = os.path.join(ROOT, "textures", name)
        with open(path, "w") as fh:
            fh.write(make())
        print("wrote", path)
